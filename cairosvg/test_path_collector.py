"""
Tests for the optional path collection and hit-testing interface.

"""

import pytest

from . import PathCollector, svg2png


def collect(svg, **kwargs):
    """Render ``svg`` to PNG while collecting painted paths."""
    collector = PathCollector()
    png = svg2png(bytestring=svg, path_collector=collector, **kwargs)
    assert png.startswith(b'\211PNG\r\n\032\n')
    return collector


def segment_points(segments):
    """Return only the coordinates of ``segments``, for easy comparison."""
    result = []
    for segment in segments:
        op = segment[0]
        if op == 'close':
            result.append(('close', ()))
        elif op == 'curve':
            result.append((op, tuple(
                (pytest.approx(x), pytest.approx(y))
                for x, y in segment[1])))
        else:
            x, y = segment[1]
            result.append((op, (pytest.approx(x), pytest.approx(y))))
    return result


def test_translated_triangle():
    """A translated triangle: hand-computed segments and point hits."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <g transform="translate(10, 20)">
            <path id="tri" d="M 0 0 L 30 0 L 0 30 Z" fill="blue"/>
          </g>
        </svg>''')

    # One painted path, in draw order
    assert len(collector.paths) == 1
    path = collector.paths[0]
    assert path.id == 'tri'
    assert path.tag == 'path'
    assert path.closed

    # Vertices (0, 0) (30, 0) (0, 30) translated by (10, 20)
    assert segment_points(path.segments) == [
        ('move', (10, 20)),
        ('line', (40, 20)),
        ('line', (10, 50)),
        ('close', ()),
    ]

    # Inside the triangle (x >= 10, y >= 20, x + y <= 60)…
    assert collector.hit(15, 25) == [path]
    assert path.contains(38, 21)
    # …and outside of it
    assert collector.hit(35, 45) == []
    assert collector.hit(5, 5) == []
    assert not path.contains(10, 60)


def test_nested_transforms():
    """Nested transforms: hand-computed rectangle corners."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <g transform="translate(10, 0)">
            <g transform="translate(0, 5) scale(2)">
              <rect id="r" x="1" y="1" width="4" height="3"/>
            </g>
          </g>
        </svg>''')

    assert len(collector.paths) == 1
    path = collector.paths[0]
    assert path.id == 'r'
    assert path.closed

    # (1, 1) -> scale(2) -> (2, 2) -> translate(0, 5) -> (2, 7)
    #         -> translate(10, 0) -> (12, 7)
    # (5, 4) -> (10, 8) -> (10, 13) -> (20, 13)
    assert segment_points(path.segments) == [
        ('move', (12, 7)),
        ('line', (20, 7)),
        ('line', (20, 13)),
        ('line', (12, 13)),
        ('close', ()),
    ]

    assert collector.hit(16, 10) == [path]
    assert collector.hit(5, 5) == []
    assert collector.hit(25, 10) == []


def test_overlapping_shapes():
    """Two overlapping rectangles: hits are reported in draw order."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <rect id="a" x="0" y="0" width="30" height="30"/>
          <rect id="b" x="15" y="15" width="30" height="30"/>
        </svg>''')

    assert len(collector.paths) == 2
    path_a, path_b = collector.paths
    assert (path_a.id, path_b.id) == ('a', 'b')

    assert collector.hit(7, 7) == [path_a]  # in a only
    assert collector.hit(37, 37) == [path_b]  # in b only
    assert collector.hit(22, 22) == [path_a, path_b]  # in both, draw order
    assert collector.hit(50, 50) == []  # in neither


def test_fill_rules():
    """A path with a hole: hit depends on the fill rule."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <path id="donut" fill-rule="evenodd"
                d="M 0 0 L 40 0 L 40 40 L 0 40 Z
                   M 10 10 L 30 10 L 30 30 L 10 30 Z"/>
        </svg>''')

    assert len(collector.paths) == 1
    path = collector.paths[0]
    assert path.fill_rule == 'evenodd'

    # The element's own evenodd rule makes the center a hole…
    assert collector.hit(20, 20) == []
    assert collector.hit(5, 5) == [path]
    # …but the nonzero rule fills it (both subpaths wind the same way)
    assert collector.hit(20, 20, fill_rule='nonzero') == [path]
    assert path.contains(20, 20, fill_rule='nonzero')
    assert not path.contains(20, 20)


def test_use():
    """Paths generated by <use> are collected with the referenced id."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <defs>
            <rect id="shape" x="0" y="0" width="10" height="10"/>
          </defs>
          <use href="#shape" x="5" y="6"/>
        </svg>''')

    # The rect in defs is not painted; only the use instance is
    assert len(collector.paths) == 1
    path = collector.paths[0]
    assert path.id == 'shape'
    assert path.tag == 'rect'
    assert path.closed

    # The use element translates the rect by (5, 6)
    assert segment_points(path.segments) == [
        ('move', (5, 6)),
        ('line', (15, 6)),
        ('line', (15, 16)),
        ('line', (5, 16)),
        ('close', ()),
    ]

    assert collector.hit(7, 8) == [path]
    assert collector.hit(20, 20) == []


def test_clip_path():
    """A clipped shape gives no hit in the clipped-away region."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <defs>
            <clipPath id="clip">
              <rect x="0" y="0" width="20" height="100"/>
            </clipPath>
          </defs>
          <rect id="clipped" x="0" y="0" width="100" height="100"
                clip-path="url(#clip)"/>
        </svg>''')

    # The clip path itself paints nothing: only the clipped rect is collected
    assert len(collector.paths) == 1
    path = collector.paths[0]
    assert path.id == 'clipped'

    assert collector.hit(10, 50) == [path]  # inside the clip region
    assert collector.hit(50, 50) == []  # clipped away


def test_empty_paths():
    """Empty paths are collected but never hit."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <path id="empty" d=""/>
          <path id="move-only" d="M 10 10"/>
          <rect id="rect" x="0" y="0" width="10" height="10"/>
        </svg>''')

    assert [path.id for path in collector.paths] == [
        'empty', 'move-only', 'rect']
    empty, move_only, rect = collector.paths
    assert empty.segments == ()
    assert move_only.segments == ()
    assert not empty.closed
    # Empty paths never hit, even inside the canvas
    assert collector.hit(5, 5) == [rect]
    assert collector.hit(10, 10) == []


def test_shapes():
    """Basic shapes: path count, closed state and simple hits."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <circle id="circle" cx="20" cy="20" r="10"/>
          <ellipse id="ellipse" cx="60" cy="20" rx="15" ry="5"/>
          <line id="line" x1="0" y1="50" x2="20" y2="50"/>
          <polyline id="polyline" points="30,50 40,50 40,60"/>
          <polygon id="polygon" points="50,50 70,50 60,70"/>
        </svg>''')

    assert [path.id for path in collector.paths] == [
        'circle', 'ellipse', 'line', 'polyline', 'polygon']
    circle, ellipse, line, polyline, polygon = collector.paths

    # Circles, ellipses and polygons are closed, lines and polylines are not
    assert circle.closed
    assert ellipse.closed
    assert not line.closed
    assert not polyline.closed
    assert polygon.closed

    # Circles and ellipses are drawn as curves
    assert any(
        segment[0] == 'curve' for segment in circle.segments)
    assert any(
        segment[0] == 'curve' for segment in ellipse.segments)

    assert collector.hit(20, 20) == [circle]  # circle center
    assert collector.hit(60, 20) == [ellipse]  # ellipse center
    assert collector.hit(60, 60) == [polygon]
    # Strokes are not part of the fill region
    assert collector.hit(10, 50) == []


def test_hidden_elements_not_collected():
    """Elements that paint nothing are not collected."""
    collector = collect(b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <rect id="hidden" x="0" y="0" width="10" height="10"
                visibility="hidden"/>
          <rect id="undisplayed" x="0" y="0" width="10" height="10"
                display="none"/>
          <rect id="painted" x="20" y="20" width="10" height="10"/>
        </svg>''')

    assert [path.id for path in collector.paths] == ['painted']
    assert collector.hit(5, 5) == []
    assert len(collector.hit(25, 25)) == 1


def test_disabled_by_default():
    """Without a collector, rendering output is strictly unchanged."""
    svg = b'''
        <svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
          <g transform="translate(10, 20)">
            <path id="tri" d="M 0 0 L 30 0 L 0 30 Z" fill="blue"/>
          </g>
          <rect x="50" y="50" width="20" height="20" fill="red"/>
        </svg>'''
    plain = svg2png(bytestring=svg)
    collector = PathCollector()
    collected = svg2png(bytestring=svg, path_collector=collector)
    assert plain == collected
    assert len(collector.paths) == 2
